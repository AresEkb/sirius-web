import { cleanup, fireEvent, render } from '@testing-library/react';
import { ReactNode } from 'react';
import { DraggableEventHandler } from 'react-draggable';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { TemporaryMovingLine } from '../BendPoint';

const drag = vi.hoisted(() => ({
  handlers: {} as Record<'onStart' | 'onDrag' | 'onStop', DraggableEventHandler>,
}));
vi.mock('@xyflow/react', () => ({ useStore: () => 1 }));
vi.mock('react-draggable', () => ({
  default: ({ children, ...props }: { children: ReactNode } & typeof drag.handlers) => {
    drag.handlers = props;
    return children;
  },
}));

afterEach(() => {
  cleanup();
  vi.runOnlyPendingTimers();
  vi.useRealTimers();
});

describe('TemporaryMovingLine', () => {
  it.each([true, false])('only suppresses the click generated by the same release after movement: %s', (moved) => {
    vi.useFakeTimers();
    const onPaneClick = vi.fn();
    const onDragStop = vi.fn();
    const ui = render(
      <div onClick={onPaneClick} data-testid="pane">
        <svg>
          <TemporaryMovingLine
            x={0}
            y={0}
            direction="x"
            segmentLength={40}
            index={0}
            onDragStart={vi.fn()}
            onDrag={vi.fn()}
            onDragStop={onDragStop}
          />
        </svg>
      </div>
    );
    const node = ui.getByTestId('temporary-moving-line-0');
    const pane = ui.getByTestId('pane');
    const point = { clientX: 20, clientY: 30, button: 0 };
    const data = { node, x: 20, y: 30, deltaX: 0, deltaY: moved ? 10 : 0, lastX: 20, lastY: 20 };
    drag.handlers.onStart(new MouseEvent('mousedown'), data);
    drag.handlers.onDrag(new MouseEvent('mousemove'), data);
    drag.handlers.onStop(new MouseEvent('mouseup', point), data);
    expect(onDragStop).toHaveBeenCalledOnce();

    fireEvent.click(pane, { ...point, detail: 1, clientX: point.clientX + 1 });
    expect(onPaneClick).toHaveBeenCalledTimes(1);
    fireEvent.click(pane, { ...point, detail: 1 });
    expect(onPaneClick).toHaveBeenCalledTimes(moved ? 1 : 2);
    vi.runOnlyPendingTimers();
    fireEvent.click(pane, { ...point, detail: 1 });
    expect(onPaneClick).toHaveBeenCalledTimes(moved ? 2 : 3);
  });
});
